/**
 * The generated Network schemas (ADR 0018) match the committed operation inventory and the
 * pinned vendor artefact. Runs offline; `npm run api:reconcile` additionally regenerates the
 * module from the vendor cache and fails if it is stale.
 */
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import * as generated from '../../packages/unifi-network/src/generated/network-11.0.97.ts';

const ROOT = join(import.meta.dirname, '../..');
const SPEC = join(ROOT, 'api-specs/network/11.0.97');
const MODULE = join(ROOT, 'packages/unifi-network/src/generated/network-11.0.97.ts');

interface Inventory {
  operations: { method: string; path: string; vendorOperationId: string }[];
}
interface Provenance {
  artifacts: { role: string; sha256: string }[];
}

const inventory = JSON.parse(await readFile(join(SPEC, 'operations.json'), 'utf8')) as Inventory;
const provenance = JSON.parse(await readFile(join(SPEC, 'provenance.json'), 'utf8')) as Provenance;
const operations = generated.OPERATIONS as Record<
  string,
  {
    method: string;
    path: string;
    queryParameters: readonly string[];
    hasBody: boolean;
    input: { safeParse(v: unknown): { success: boolean }; shape: Record<string, unknown> };
  }
>;

describe('generated Network 11.0.97 schemas', () => {
  it('were generated from the pinned contract artefact', async () => {
    const source = await readFile(MODULE, 'utf8');
    const contract = provenance.artifacts.find((a) => a.role === 'contract');
    expect(source).toContain(`SHA-256: ${contract?.sha256 ?? 'missing'}`);
    expect(source).toMatch(/^\/\*\*\n \* GENERATED by scripts\/generate-adapter-schemas\.ts/);
  });

  it('cover exactly the documented operations, with the same method and path', () => {
    expect(Object.keys(operations).sort()).toEqual(
      inventory.operations.map((op) => op.vendorOperationId).sort(),
    );
    for (const op of inventory.operations) {
      expect(operations[op.vendorOperationId], op.vendorOperationId).toMatchObject({
        method: op.method,
        path: op.path,
      });
    }
  });

  it('take siteId as a target, never as an argument, and reject unknown arguments', () => {
    for (const [id, op] of Object.entries(operations)) {
      expect(Object.keys(op.input.shape), id).not.toContain('siteId');
      expect(op.input.safeParse({ unexpected: 1 }).success, id).toBe(false);
    }
  });

  it('place every argument in the path, the query or the body', () => {
    for (const [id, op] of Object.entries(operations)) {
      const placeholders = [...op.path.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
      for (const name of Object.keys(op.input.shape)) {
        const placed =
          placeholders.includes(name) ||
          op.queryParameters.includes(name) ||
          (name === 'body' && op.hasBody);
        expect(placed, `${id}.${name}`).toBe(true);
      }
    }
  });

  it('leave out the ambiguous device-tag filter (ADR 0018)', () => {
    expect(operations['getDeviceTagPage']?.queryParameters).not.toContain('filter');
    expect(operations['getDeviceTagPage']?.input.safeParse({ filter: 'x' }).success).toBe(false);
  });
});
