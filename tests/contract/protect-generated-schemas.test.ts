/**
 * The generated Protect schemas (ADR 0019) match the committed operation inventory and the
 * pinned vendor artefact. Runs offline; `npm run api:reconcile` additionally regenerates the
 * module from the vendor cache and fails if it is stale.
 */
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import * as generated from '../../packages/unifi-protect/src/generated/protect-7.4.96.ts';

const ROOT = join(import.meta.dirname, '../..');
const SPEC = join(ROOT, 'api-specs/protect/7.4.96');
const MODULE = join(ROOT, 'packages/unifi-protect/src/generated/protect-7.4.96.ts');
const UPLOAD = 'POST /v1/files/{fileType}';

interface Inventory {
  operations: { key: string; method: string; path: string; transport: string }[];
}
interface Provenance {
  artifacts: { role: string; sha256: string }[];
}

const inventory = JSON.parse(await readFile(join(SPEC, 'operations.json'), 'utf8')) as Inventory;
const provenance = JSON.parse(await readFile(join(SPEC, 'provenance.json'), 'utf8')) as Provenance;
const operations = generated.OPERATIONS as Record<
  string,
  {
    method: string;
    path: string;
    transport: string;
    queryParameters: readonly string[];
    hasBody: boolean;
    responseType: string;
    input: { safeParse(v: unknown): { success: boolean }; shape: Record<string, unknown> };
    output: { safeParse(v: unknown): { success: boolean } };
  }
>;

describe('generated Protect 7.4.96 schemas', () => {
  it('were generated from the pinned contract artefact', async () => {
    const source = await readFile(MODULE, 'utf8');
    const contract = provenance.artifacts.find((a) => a.role === 'contract');
    expect(source).toContain(`SHA-256: ${contract?.sha256 ?? 'missing'}`);
    expect(source).toMatch(/^\/\*\*\n \* GENERATED by scripts\/generate-adapter-schemas\.ts/);
  });

  it('cover every documented operation except the reviewed upload, keyed by method and path', () => {
    expect(Object.keys(operations).sort()).toEqual(
      inventory.operations
        .map((op) => op.key)
        .filter((key) => key !== UPLOAD)
        .sort(),
    );
    for (const op of inventory.operations.filter((o) => o.key !== UPLOAD)) {
      expect(operations[op.key], op.key).toMatchObject({
        method: op.method,
        path: op.path,
        transport: op.transport,
      });
    }
  });

  it('leave out the multipart upload, whose form field is undocumented (ADR 0019)', async () => {
    expect(operations[UPLOAD]).toBeUndefined();
    expect(await readFile(MODULE, 'utf8')).toContain(`// Operation "${UPLOAD}" omitted:`);
  });

  it('reject unknown arguments and place every argument in the path, query or body', () => {
    for (const [key, op] of Object.entries(operations)) {
      expect(op.input.safeParse({ unexpected: 1 }).success, key).toBe(false);
      const placeholders = [...op.path.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
      for (const name of Object.keys(op.input.shape)) {
        const placed =
          placeholders.includes(name) ||
          op.queryParameters.includes(name) ||
          (name === 'body' && op.hasBody);
        expect(placed, `${key}.${name}`).toBe(true);
      }
    }
  });

  it('return the snapshot as bytes, and every other response as JSON or nothing', () => {
    for (const [key, op] of Object.entries(operations)) {
      const expected = key === 'GET /v1/cameras/{id}/snapshot' ? 'image/jpeg' : ['json', 'none'];
      if (typeof expected === 'string') expect(op.responseType, key).toBe(expected);
      else expect(expected, key).toContain(op.responseType);
    }
    const snapshot = operations['GET /v1/cameras/{id}/snapshot'];
    expect(snapshot?.output.safeParse(new Uint8Array([0xff, 0xd8, 0xff])).success).toBe(true);
    expect(snapshot?.output.safeParse({ url: 'x' }).success).toBe(false);
  });

  it('mark exactly the three documented subscriptions as WebSocket', () => {
    expect(
      Object.entries(operations)
        .filter(([, op]) => op.transport === 'websocket')
        .map(([key]) => key)
        .sort(),
    ).toEqual([
      'GET /v1/subscribe/devices',
      'GET /v1/subscribe/events',
      'GET /v1/subscribe/updates',
    ]);
  });

  it('keep the narrowed microphone volume usable (1–100)', () => {
    const patch = operations['PATCH /v1/cameras/{id}'];
    const camera = (micVolume: number) => ({ id: 'a'.repeat(24), body: { micVolume } });
    expect(patch?.input.safeParse(camera(1)).success).toBe(true);
    expect(patch?.input.safeParse(camera(100)).success).toBe(true);
    expect(patch?.input.safeParse(camera(0)).success).toBe(false);
  });
});
